#!/usr/bin/env node
/**
 * Dependency-free lint: `node --check` every JS file, JSON-parse the example
 * config, and keep lib/cli.js VERSION in sync with package.json.
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (entry === 'node_modules' || entry === '__pycache__') continue;
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (/\.(js|mjs)$/.test(entry)) out.push(full);
  }
  return out;
}

let failed = 0;
// dist/ is regenerated by `npm run build` right after linting; build self-checks it.
const targets = [
  ...walk(join(root, 'lib')),
  ...walk(join(root, 'scripts')),
  ...walk(join(root, 'tests')),
];

for (const file of targets) {
  const result = spawnSync(process.execPath, ['--check', file], { encoding: 'utf8' });
  if (result.status !== 0) {
    failed += 1;
    console.error(`FAIL node --check ${file}\n${result.stderr}`);
  }
}

const example = join(root, '..', 'cortiq-router.example.json');
try {
  JSON.parse(readFileSync(example, 'utf8'));
  console.log('ok    cortiq-router.example.json parses');
} catch (error) {
  failed += 1;
  console.error(`FAIL cortiq-router.example.json: ${error.message}`);
}

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const cliSource = readFileSync(join(root, 'lib', 'cli.js'), 'utf8');
const version = /export const VERSION = '([^']+)'/.exec(cliSource)?.[1];
if (version !== pkg.version) {
  failed += 1;
  console.error(`FAIL VERSION ${version} != package.json ${pkg.version}`);
} else {
  console.log(`ok    VERSION ${version} matches package.json`);
}

if (failed === 0) console.log(`ok    node --check: ${targets.length} files`);
process.exit(failed === 0 ? 0 : 1);